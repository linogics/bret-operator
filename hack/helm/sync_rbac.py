#!/usr/bin/env python3
"""Render the RBAC rules from config/rbac into the Helm chart templates.

Kubebuilder generates config/rbac/role.yaml (manager rules), leader_election_role.yaml and
metrics_auth_role.yaml. The chart must carry the same rules. This script copies the rules and
writes templates/rbac-rules.yaml with Helm names. Bindings live in templates/rbac.yaml.

usage: sync_rbac.py CONFIG_RBAC_DIR CHART_TEMPLATES_DIR
"""
import sys
from pathlib import Path

import yaml

HEADER = """# Generated by hack/helm/sync_rbac.py from config/rbac. Do not edit by hand.
{{- $fullname := include "bret-operator.fullname" . }}
"""


# API groups of the optional providers and the chart value that enables each of them.
PROVIDER_GROUPS = {
    "kopiur.home-operations.com": "kopiur",
    "velero.io": "velero",
    "volsync.backube": "volsync",
}


def provider_rules(rules, pod_cond=None):
    """Dump rules, wrapping every provider rule in its providers.<name> condition.

    The pods and PVC rule gets pod_cond: it is cluster-wide only with Velero on or no watched namespaces.
    """
    out = []
    for rule in rules:
        text = yaml.safe_dump([rule], sort_keys=False)
        name = PROVIDER_GROUPS.get(rule["apiGroups"][0])
        # Namespace rights exist only for the Velero scratch namespace.
        if rule["resources"] == ["namespaces"]:
            name = "velero"
        # VolSync restores read the repository secret, so the secrets rule rides with volsync.
        if rule["resources"] == ["secrets"]:
            name = "volsync"
        # Velero copies the check's Secrets and ConfigMaps into the scratch namespace.
        if "configmaps" in rule["resources"]:
            name = "velero"
        if "pods" in rule["resources"]:
            text = f"{{{{- if {pod_cond} }}}}\n{text}{{{{- end }}}}\n"
        elif name:
            text = f"{{{{- if $.Values.providers.{name}.enabled }}}}\n{text}{{{{- end }}}}\n"
        out.append(text)
    return "".join(out)


def load_rules(path: Path):
    with path.open() as f:
        doc = yaml.safe_load(f)
    return doc["rules"]


def main():
    rbac_dir = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])

    manager = load_rules(rbac_dir / "role.yaml")
    leader = load_rules(rbac_dir / "leader_election_role.yaml")
    metrics = load_rules(rbac_dir / "metrics_auth_role.yaml")

    parts = [HEADER]
    parts.append(
        """---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: {{ $fullname }}-manager
  labels:
    {{- include "bret-operator.labels" . | nindent 4 }}
"""
    )
    # Namespaces and events stay cluster-wide. Pods and PVCs are cluster-wide only with Velero on,
    # because its scratch namespaces are not watched; otherwise they move to the per-namespace Roles.
    # controller-gen merges the secrets rights of VolSync and Velero into one rule. The Velero rule copies
    # into the unwatched scratch namespace, so it stays cluster-wide. VolSync only reads the repository
    # secret, so it gets its own get rule that goes with the cluster-wide rules or the per-namespace Roles.
    core = [r for r in manager if r["apiGroups"] == [""]]
    pods = [r for r in core if "pods" in r["resources"]]
    volsync_secrets = {"apiGroups": [""], "resources": ["secrets"], "verbs": ["get"]}
    rest = [volsync_secrets] + [r for r in manager if r["apiGroups"] != [""]]
    parts.append(
        "rules:\n"
        + provider_rules(core, "or (not .Values.watchNamespaces) $.Values.providers.velero.enabled")
    )
    parts.append("{{- if not .Values.watchNamespaces }}\n" + provider_rules(rest) + "{{- end }}\n")
    parts.append(
        """{{- range .Values.watchNamespaces }}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {{ $fullname }}-manager
  namespace: {{ . }}
  labels:
    {{- include "bret-operator.labels" $ | nindent 4 }}
rules:
"""
        + provider_rules(pods, "not $.Values.providers.velero.enabled")
        + provider_rules([r for r in rest if r["apiGroups"] != ["velero.io"]])
        + """{{- end }}
{{- if and $.Values.watchNamespaces $.Values.providers.velero.enabled }}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {{ $fullname }}-velero
  namespace: {{ $.Values.providers.velero.namespace }}
  labels:
    {{- include "bret-operator.labels" $ | nindent 4 }}
rules:
"""
        + yaml.safe_dump([r for r in rest if r["apiGroups"] == ["velero.io"]], sort_keys=False)
        + """{{- end }}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {{ $fullname }}-leader-election
  namespace: {{ .Release.Namespace }}
  labels:
    {{- include "bret-operator.labels" . | nindent 4 }}
"""
    )
    parts.append(yaml.safe_dump({"rules": leader}, sort_keys=False))
    parts.append(
        """---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: {{ $fullname }}-metrics-auth
  labels:
    {{- include "bret-operator.labels" . | nindent 4 }}
"""
    )
    parts.append(yaml.safe_dump({"rules": metrics}, sort_keys=False))

    (out_dir / "rbac-rules.yaml").write_text("".join(parts))
    print(f"wrote {out_dir / 'rbac-rules.yaml'}")


if __name__ == "__main__":
    main()
