#!/usr/bin/env python3
"""Render the RBAC rules from config/rbac into the Helm chart templates.

Kubebuilder generates config/rbac/role.yaml (manager rules), leader_election_role.yaml and
metrics_auth_role.yaml. The chart must carry the same rules. This script copies the rules and
writes templates/rbac-rules.yaml with Helm names. Bindings live in templates/rbac.yaml.

usage: sync_rbac.py CONFIG_RBAC_DIR CHART_TEMPLATES_DIR
"""
import sys
from pathlib import Path

import yaml

HEADER = """# Generated by hack/helm/sync_rbac.py from config/rbac. Do not edit by hand.
{{- $fullname := include "bret-operator.fullname" . }}
"""


def load_rules(path: Path):
    with path.open() as f:
        doc = yaml.safe_load(f)
    return doc["rules"]


def main():
    rbac_dir = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])

    manager = load_rules(rbac_dir / "role.yaml")
    leader = load_rules(rbac_dir / "leader_election_role.yaml")
    metrics = load_rules(rbac_dir / "metrics_auth_role.yaml")

    parts = [HEADER]
    parts.append(
        """---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: {{ $fullname }}-manager
  labels:
    {{- include "bret-operator.labels" . | nindent 4 }}
"""
    )
    parts.append(yaml.safe_dump({"rules": manager}, sort_keys=False))
    parts.append(
        """---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {{ $fullname }}-leader-election
  namespace: {{ .Release.Namespace }}
  labels:
    {{- include "bret-operator.labels" . | nindent 4 }}
"""
    )
    parts.append(yaml.safe_dump({"rules": leader}, sort_keys=False))
    parts.append(
        """---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: {{ $fullname }}-metrics-auth
  labels:
    {{- include "bret-operator.labels" . | nindent 4 }}
"""
    )
    parts.append(yaml.safe_dump({"rules": metrics}, sort_keys=False))

    (out_dir / "rbac-rules.yaml").write_text("".join(parts))
    print(f"wrote {out_dir / 'rbac-rules.yaml'}")


if __name__ == "__main__":
    main()
